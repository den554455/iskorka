"""Собирает кандидатов на проверку ударений: слова из сценариев, где озвучка может ошибиться.

Запуск (из корня проекта):  python -m scripts.stress_candidates > STRESS_CANDIDATES.md

Скрипт ничего не исправляет и `_STRESS` не меняет: только показывает, где слово встречается,
чтобы эти фразы можно было прослушать в консоли Диалогов. Колонка «гипотеза» — предположение
об ударной форме, а не подтверждённый факт.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

CONTENT = Path(__file__).resolve().parent.parent / "app" / "content"

# (регулярное выражение слова, гипотеза об ударении, почему слово в списке)
CANDIDATES = [
    (r"Искорк\w*", "И+скорка", "имя героини"),
    (r"Тиш\w*", "Т+иша", "имя совёнка"),
    (r"Пуговк\w*", "П+уговка", "имя зайчонка"),
    (r"Кап\w*", "К+ап", "имя духа ручья; «Кап-кап» — звукоподражание"),
    (r"[Хх]ранител\w*", "хранит+ель", "персонаж эпизодов 27–30"),
    (r"ветряно\w*|ветряк\w*", "ветрян+ой", "редкое слово"),
    (r"мерца\w*", "мерц+ает", "глагол"),
    (r"\bузнаем\b|\bузнаём\b", "узн+аем", "«узнаем/узнаём» — форма на слух"),
    (r"\bслова\b", "слов+а / сл+ова", "омограф: мн. ч. и род. п. ед. ч."),
    (r"\bберега\b", "берег+а", "омограф: мн. ч. и род. п. ед. ч."),
    (r"\bдоски\b|\bдосок\b", "д+оски", "омограф: доски́ (род. п.)"),
    (r"\bоблака\b|\bоблако\b", "облак+а", "омограф: форма зависит от падежа"),
    (r"\bруки\b|\bноги\b|\bголовы\b", "рук+и / р+уки", "омограф: форма зависит от падежа"),
    (r"\bводу\b|\bводы\b|\bземлю\b", "в+оду / вод+ы", "ударение вправо/влево зависит от падежа"),
    (r"\bугл\w*", "углы+", "омограф: форма зависит от падежа"),
    (r"\bдорожки\b", "дор+ожки / дорожк+и", "омограф"),
    (r"\bлепестки\b", "лепестк+и", "окончание"),
    (r"\bколыбельн\w*", "колыб+ельная", "длинное слово"),
    (r"\bземляник\w*", "землян+ика", "длинное слово"),
    (r"\bвертушк\w*", "верт+ушка", "слово из эпизода 4"),
    (r"\bшкатулк\w*", "шкат+улка", "слово из эпизода 26"),
    (r"\bухн\w*", "+ухнул", "звукоподражательный глагол"),
    (r"\bуже\b", "уж+е / +уже", "омограф: «уже́/у́же»"),
    (r"\bпарит\b", "пар+ит / п+арит", "омограф: «парит» в воздухе / «парит» в бане"),
]


def _texts(value):
    if isinstance(value, str):
        yield value
    elif isinstance(value, list):
        for v in value:
            yield from _texts(v)
    elif isinstance(value, dict):
        for v in value.values():
            yield from _texts(v)


def main() -> None:
    texts: list[tuple[str, str]] = []
    for path in sorted((CONTENT / "episodes").glob("ep*.json"), key=lambda p: int(p.stem[2:])):
        data = json.loads(path.read_text(encoding="utf-8"))
        for node, body in data["nodes"].items():
            for field in ("say", "ask", "resume", "reask", "hint"):
                for t in _texts(body.get(field)):
                    texts.append((f"{path.stem}/{node}", re.sub(r"\[[^\]]*\]\s*", "", t)))
    out = sys.stdout
    print("# Кандидаты на проверку ударений\n")
    print("Статус: **на слух не проверялось**. Это список слов, которые стоит прослушать; в `_STRESS` они не добавлены.\n")
    print("| Слово (шаблон) | Гипотеза | Почему | Встреч | Пример (эпизод/узел) |")
    print("|---|---|---|---|---|")
    for rx, hypo, why in CANDIDATES:
        pat = re.compile(rx)
        hits = [(w, t) for w, t in texts if pat.search(t)]
        if not hits:
            continue
        where, text = hits[0]
        m = pat.search(text)
        ctx = text[max(0, m.start() - 30): m.end() + 25].replace("|", "/").replace("\n", " ")
        print(f"| `{rx}` | {hypo} | {why} | {len(hits)} | {where}: …{ctx}… |")
    print("\n## Что нужно для проверки\n")
    print("1. Тестовый навык в консоли Диалогов: пройти эпизоды и записать (или прослушать) озвученные реплики.")
    print("2. Для каждого слова из таблицы отметить: «верно» / «неверно» (и как прозвучало) / «неестественно».")
    print("3. Только для отмеченных «неверно» добавить правило в `_STRESS` (`app/audio.py`) и тест в `tests/test_stress.py`.")


if __name__ == "__main__":
    main()
